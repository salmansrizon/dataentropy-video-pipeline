// A band that rests on each row in turn: [frames], [y positions] for kf, and when row r is tested.
const band = (t0: number, n: number, rowY: (r: number) => number, perRow = 24, move = 18) => ({
	frames: Array.from({length: n}, (_, r) => [t0 + r * perRow, t0 + (r + 1) * perRow - move]).flat(),
	ys: Array.from({length: n}, (_, r) => [rowY(r), rowY(r)]).flat(),
	at: (r: number) => t0 + r * perRow + 4,
	end: t0 + n * perRow,
});
const TestBand: React.FC<{f: number; b: ReturnType<typeof band>; x: number; w: number; h?: number}> = ({f, b, x, w, h = ROW_H}) => {
	const o = enter(f, [b.frames[0] - 12, b.frames[0]], [0, 1]) * fadeOut(f, b.end, 8);
	if (o <= 0) return null;
	const y = kf(f, b.frames, b.ys);
	return (
		<g opacity={o}>
			<rect x={x} y={y} width={w} height={h} fill={C.lavender} opacity={0.5} style={{mixBlendMode: 'multiply'}} />
			<rect x={x - 8} y={y} width={w + 16} height={h} rx={12} fill="none" stroke={C.violet} strokeWidth={5} />
		</g>
	);
};

// A value that travels from one place to another inside a white chip; the chip fades once it lands.
const Flyer: React.FC<{f: number; at: number; from: {x: number; y: number}; to: {x: number; y: number}; w: number; text: string; d?: number; arc?: number; size?: number; opacity?: number; color?: string}> = ({f, at, from, to, w, text, d = 40, arc = 0, size = 40, opacity = 1, color = C.navy}) => {
	const p = kf(f, [at, at + d], [0, 1]);
	if (p <= 0 || opacity <= 0) return null;
	const [x, y] = [from.x + (to.x - from.x) * p, from.y + (to.y - from.y) * p - Math.sin(p * Math.PI) * arc];
	return (
		<g opacity={opacity}>
			<rect x={x - 16} y={y - size - 2} width={w} height={size + 18} rx={12} fill={C.card} stroke={C.violet} strokeWidth={4} opacity={fadeIn(f, at, 12) * fadeOut(f, at + d - 8, 8)} />
			<text x={x} y={y} fontSize={size} fontWeight={500} fill={color}>{text}</text>
		</g>
	);
};

