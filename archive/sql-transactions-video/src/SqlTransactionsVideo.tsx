// One typed line of SQL: the first `kw` characters are the keyword, in violet.
const typedCount = (f: number, at: number, text: string) => Math.floor(kf(f, [at, at + text.length * CODE.rate], [0, text.length], EASE.linear));
const typedEnd = (at: number, text: string) => Math.ceil(at + text.length * CODE.rate);
const CodeLine: React.FC<{f: number; at: number; x: number; y: number; text: string; kw: number; opacity?: number}> = ({f, at, x, y, text, kw, opacity = 1}) => {
	const n = typedCount(f, at, text);
	if (n <= 0) return null;
	return (
		<text x={x} y={y} fontFamily={MONO} fontSize={CODE.size} fontWeight={500} fill={C.navy} opacity={opacity} style={{whiteSpace: 'pre'}}>
			<tspan fill={C.violet} fontWeight={700}>{text.slice(0, Math.min(n, kw))}</tspan>
			{text.slice(kw, Math.max(kw, n))}
		</text>
	);
};

