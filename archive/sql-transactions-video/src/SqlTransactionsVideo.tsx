// Camera stops: [start frame, x, y, scale]. Each move takes 35 frames.
const camTrack = (f: number, first: number[], stops: number[][]) => {
	const t = stops.flatMap(([at]) => [at, at + 35]);
	const track = (k: number) => kf(f, t, stops.flatMap((stop, i) => [i ? stops[i - 1][k] : first[k - 1], stop[k]]));
	return {x: track(1), y: track(2), s: track(3)};
};

